def lesson_block(pages):
    rendered = []
    for title, levels in pages:
        body = []
        for level in ("easy", "medium", "hard"):
            rows = ",\n".join("            " + json.dumps(e, ensure_ascii=False) for e in levels[level])
            body.append(f"          {level}: [\n{rows}\n          ]")
        rendered.append(f"        lv({json.dumps(title, ensure_ascii=False)}, {{\n" + ",\n".join(body) + "\n        })")
    return ("    {\n      id: 1,\n      label: \"第一課\",\n      sourceImage: \"第一張圖\",\n      pages: [\n"
            + ",\n".join(rendered) + "\n      ]\n    },\n")
